print("how are \n u") # this will print "how are" and "u" on a new line
print("how are \t u") # this will print "how are" and "u" with a tab space in between
print("how are \b u") # this will print "how are" and "u" with a backspace in between, which will remove the space
print("how are \r u") # this will print "u" and overwrite "how are" with "u" due to the carriage return 
print("how are \f u") # this will print "how are" and "u" with a form feed in between, which will move the cursor to the next line and print "u" on the next line  
print("how are \v u") # this will print "how are" and "u" with a vertical tab in between, which will move the cursor down to the next line and print "u" on the next line
print("how are \\ u") # this will print "how are \ u" with a backslash in between
print("how are \" u") # this will print "how are " u" with double quotes in between
print("how are \' u") # this will print "how are ' u" with single
print("how are \a u") # this will print "how are" and "u" with a bell sound in between, which will make a beep sound when executed
print("how are \0 u") # this will print "how are" and "u" with a null character in between, which will not be visible when executed
print("how are \x41 u") # this will print "how are A u" with the hexadecimal value 41 (which is 'A' in ASCII) in between
print("how are \u0041 u") # this will print "how are A u" with the Unicode value 0041 (which is 'A' in Unicode) in between
print("how are \U00000041 u") # this will print "how are A u" with the Unicode value 00000041 (which is 'A' in Unicode) in between
print("how are \N{LATIN CAPITAL LETTER A} u") # this will print "how are A u" with the Unicode character LATIN CAPITAL LETTER A in between  
print("how are \N{GREEK CAPITAL LETTER ALPHA} u") # this will print "how are Α u" with the Unicode character GREEK CAPITAL LETTER ALPHA in between
